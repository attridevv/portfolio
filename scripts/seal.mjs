#!/usr/bin/env node
// Seals private/personal.html into aka/vault.js (AES-256-GCM, key from PBKDF2-SHA256).
// The output is safe to publish: without the password it is unreadable.
//
//   node scripts/seal.mjs                 # asks for the password (hidden)
//   AKA_PASS='your phrase' node scripts/seal.mjs
//
// Use a long passphrase (4+ words). The encrypted file is public, so a short
// password can be guessed offline no matter how good the encryption is.

import { readFile, writeFile } from 'node:fs/promises';
import { webcrypto as crypto } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(root, 'private/personal.html');
const OUT = path.join(root, 'aka/vault.js');
const ITER = 600_000;

function askHidden(q) {
  return new Promise((resolve) => {
    const { stdin, stdout } = process;
    stdout.write(q);
    stdin.setRawMode?.(true);
    stdin.resume();
    stdin.setEncoding('utf8');
    let s = '';
    stdin.on('data', function on(ch) {
      if (ch === '\r' || ch === '\n' || ch === '\u0004') {
        stdin.setRawMode?.(false); stdin.pause(); stdin.off('data', on); stdout.write('\n'); resolve(s);
      } else if (ch === '\u0003') { process.exit(1); }
      else if (ch === '\u007f') { s = s.slice(0, -1); }
      else { s += ch; }
    });
  });
}

const b64 = (u8) => Buffer.from(u8).toString('base64');

let pass = process.env.AKA_PASS;
if (!pass) {
  pass = await askHidden('Password for the personal portal: ');
  const again = await askHidden('Repeat it: ');
  if (pass !== again) { console.error('Passwords do not match.'); process.exit(1); }
}
if (!pass || pass.length < 8) { console.error('Use at least 8 characters (a 4-word phrase is best).'); process.exit(1); }

const html = (await readFile(SRC, 'utf8')).replace(/^\s*<!--[\s\S]*?-->\s*/, '');
const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));
const base = await crypto.subtle.importKey('raw', new TextEncoder().encode(pass.normalize('NFC')), 'PBKDF2', false, ['deriveKey']);
const key = await crypto.subtle.deriveKey({ name: 'PBKDF2', salt, iterations: ITER, hash: 'SHA-256' }, base, { name: 'AES-GCM', length: 256 }, false, ['encrypt']);
const ct = new Uint8Array(await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, key, new TextEncoder().encode(html)));

const out = `// Encrypted personal content. Generated by scripts/seal.mjs — do not edit by hand.\nwindow.VAULT=${JSON.stringify({ v: 1, iter: ITER, salt: b64(salt), iv: b64(iv), ct: b64(ct) })};\n`;
await writeFile(OUT, out);
console.log(`Sealed ${html.length.toLocaleString()} chars → ${path.relative(root, OUT)} (${out.length.toLocaleString()} bytes)`);
